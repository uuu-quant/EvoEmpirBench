import importlib.util
import io
import json
import os
import random
import sys
import types
from copy import deepcopy
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional


PROJECT_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_JSON = PROJECT_ROOT / "docs" / "assets" / "cases" / "learning-traces.json"
OUTPUT_JS = PROJECT_ROOT / "docs" / "assets" / "cases" / "learning-traces.js"


def install_headless_import_stubs() -> None:
    """Install tiny stubs for optional UI/API imports when unavailable."""

    os.environ.setdefault("SDL_VIDEODRIVER", "dummy")

    if "gymnasium" not in sys.modules and importlib.util.find_spec("gymnasium") is None:
        class Env:
            def reset(self, seed: Optional[int] = None) -> None:
                return None

        class Discrete:
            def __init__(self, n: int):
                self.n = n

        class Box:
            def __init__(self, low: int, high: int, shape: Iterable[int], dtype: Any):
                self.low = low
                self.high = high
                self.shape = tuple(shape)
                self.dtype = dtype

        gymnasium = types.ModuleType("gymnasium")
        gymnasium.Env = Env
        gymnasium.spaces = types.SimpleNamespace(Discrete=Discrete, Box=Box)
        sys.modules["gymnasium"] = gymnasium

    if "pygame" not in sys.modules and importlib.util.find_spec("pygame") is None:
        pygame = types.ModuleType("pygame")
        pygame.SRCALPHA = 0
        pygame.QUIT = 0
        pygame.init = lambda: None
        pygame.quit = lambda: None
        pygame.display = types.SimpleNamespace(
            set_mode=lambda size: types.SimpleNamespace(
                fill=lambda *args, **kwargs: None,
                blit=lambda *args, **kwargs: None,
            ),
            set_caption=lambda *args, **kwargs: None,
            flip=lambda: None,
        )
        pygame.time = types.SimpleNamespace(
            Clock=lambda: types.SimpleNamespace(tick=lambda *args, **kwargs: None),
            wait=lambda *args, **kwargs: None,
        )
        pygame.font = types.SimpleNamespace(
            init=lambda: None,
            Font=lambda *args, **kwargs: types.SimpleNamespace(
                render=lambda *args, **kwargs: None
            ),
        )
        pygame.Surface = lambda *args, **kwargs: types.SimpleNamespace()
        pygame.Rect = lambda *args, **kwargs: tuple(args)
        pygame.draw = types.SimpleNamespace(
            line=lambda *args, **kwargs: None,
            rect=lambda *args, **kwargs: None,
            circle=lambda *args, **kwargs: None,
            polygon=lambda *args, **kwargs: None,
        )
        pygame.event = types.SimpleNamespace(get=lambda: [])
        sys.modules["pygame"] = pygame

    if "openai" not in sys.modules and importlib.util.find_spec("openai") is None:
        openai = types.ModuleType("openai")

        class OpenAI:
            def __init__(self, *args: Any, **kwargs: Any):
                pass

        openai.OpenAI = OpenAI
        sys.modules["openai"] = openai


def to_builtin(value: Any) -> Any:
    if hasattr(value, "tolist"):
        return value.tolist()
    if isinstance(value, dict):
        return {key: to_builtin(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set)):
        return [to_builtin(item) for item in value]
    if hasattr(value, "item"):
        return value.item()
    return value


def action_name(action: Optional[int]) -> Optional[str]:
    if action is None:
        return None
    directions = ["UP", "DOWN", "LEFT", "RIGHT"]
    return f"{directions[action // 3]}{action % 3 + 1}"


def export_maze_trace() -> Dict[str, Any]:
    install_headless_import_stubs()

    from src.config.game_config import MODE_LEVEL3
    from src.game.environment import PathFindingEnv

    map_file = PROJECT_ROOT / "data" / "levels" / "maze_eval" / "Level_3_9.json"
    map_data = json.loads(map_file.read_text(encoding="utf-8"))

    before_actions = [
        9, 9, 9, 0, 0, 0, 0, 9, 9, 9,
        0, 0, 0, 9, 9, 0, 0, 0, 9, 9,
    ]
    after_actions = [
        9, 9, 9, 9, 9, 0, 0, 0, 9, 9,
        9, 9, 9, 0, 0, 0, 2, 0,
    ]

    def run_policy(name: str, actions: List[int], seed: int) -> Dict[str, Any]:
        random.seed(seed)
        env = PathFindingEnv(MODE_LEVEL3)
        env.load_map(deepcopy(map_data), 8)

        frames: List[Dict[str, Any]] = []

        def snapshot(
            action: Optional[int] = None,
            reward: int = 0,
            done: bool = False,
            event: Optional[str] = None,
        ) -> Dict[str, Any]:
            return {
                "grid": to_builtin(env.grid),
                "vision": to_builtin(env.vision_map),
                "pos": list(env.agent_pos),
                "score": int(env.score),
                "steps": int(env.steps_count),
                "lives": int(env.lives),
                "coins": [list(pos) for pos in sorted(env.coins)],
                "monsters": [list(monster.pos) for monster in env.monsters],
                "tools": {
                    "shovel": bool(env.has_shovel),
                    "sword": bool(env.has_sword),
                    "magnet": bool(env.has_magnet),
                    "key": bool(env.has_key),
                },
                "action": action,
                "actionName": action_name(action),
                "reward": int(reward),
                "done": bool(done),
                "event": event,
            }

        frames.append(snapshot())
        for action in actions:
            before_pos = tuple(env.agent_pos)
            before_key = env.has_key
            _, reward, done, _, _ = env.step(action)
            event = None
            if (
                not before_key
                and action == 9
                and before_pos == tuple(env.agent_pos)
                and tuple(env.agent_pos) == (0, 9)
            ):
                event = "goal_locked_without_key"
            if done:
                event = "goal_reached"
            frames.append(snapshot(action=action, reward=int(reward), done=done, event=event))
            if done:
                break

        metrics = {
            "score": int(env.score),
            "steps": int(env.steps_count),
            "lives": int(env.lives),
            "cleared": bool(frames[-1]["done"]),
            "toolsCollected": sum(1 for value in frames[-1]["tools"].values() if value),
            "hasKey": bool(frames[-1]["tools"]["key"]),
        }
        env.close()

        labels = {
            "before": {
                "title": "Before memory: goal rush without key",
                "phaseLabel": "executed Level 3 rollout",
                "status": "goal locked by missing key",
                "truth": "No verified rule: the agent tries the goal before collecting the key.",
            },
            "after": {
                "title": "After truth: collect tools, then enter goal",
                "phaseLabel": "executed Level 3 rollout",
                "status": "goal reached",
                "truth": "Verified rule: collect key/tools before entering the final corridor.",
            },
        }
        return {
            "policy": name,
            "source": "PathFindingEnv.step on data/levels/maze_eval/Level_3_9.json",
            **labels[name],
            "frameMs": 620,
            "frames": frames,
            "metrics": metrics,
        }

    return {
        "before": run_policy("before", before_actions, seed=1),
        "after": run_policy("after", after_actions, seed=1),
    }


def export_match_trace() -> Dict[str, Any]:
    install_headless_import_stubs()

    from src.match_game.general_game import COLOR_KEYS, COSTS, GRID_SIZE, MatchGame

    level_file = PROJECT_ROOT / "data" / "levels" / "match_game" / "easy" / "level05.json"
    level_data = json.loads(level_file.read_text(encoding="utf-8"))

    class HeadlessMatchGame(MatchGame):
        def __init__(self, level: Dict[str, Any]):
            self.model_name = "project-page-policy"
            self.auto_run = False
            self.api_client = None
            self.board = deepcopy(level["board"])
            self.score = 0
            self.steps_remaining = int(level["max_steps"])
            self.max_steps = int(level["max_steps"])
            self.steps_used = 0
            self.current_level = 5
            self.current_difficulty = "easy"
            self.is_human_mode = True
            self.is_processing = False
            self.game_over = False
            self.inventory = deepcopy(level["inventory"])
            self.selecting_prop = None
            self.levels = {"easy": [level], "medium": [], "hard": []}
            self.level_select = False
            self.message = ""
            self.message_timeout = 0
            self.action_log = []
            self.color_targets = deepcopy(level["color_targets"])
            self.color_counts = {color: 0 for color in COLOR_KEYS}
            self.total_cleared = 0
            self.clear_counts = []
            self.session_dir = ""
            self.session_timestamp = "project-page"
            self.api_response_count = 0
            self.valid_api_response_count = 0

        def save_state(self) -> None:
            return None

        def save_clear_log(self) -> None:
            return None

        def log_action(self, *args: Any, **kwargs: Any) -> None:
            return None

        def check_game_over(self) -> bool:
            targets_met = all(
                self.color_counts[color] >= self.color_targets[color]
                for color in COLOR_KEYS
            )
            if self.steps_remaining <= 0 or targets_met:
                self.game_over = True
            return self.game_over

    def connected_regions(game: HeadlessMatchGame) -> List[Dict[str, Any]]:
        regions: List[Dict[str, Any]] = []
        visited = [[False] * GRID_SIZE for _ in range(GRID_SIZE)]
        for row in range(GRID_SIZE):
            for col in range(GRID_SIZE):
                if game.board[row][col] and not visited[row][col]:
                    cells = game.find_connected_region(
                        row, col, game.board[row][col], visited, game.board
                    )
                    if len(cells) >= 2:
                        counts = {color: 0 for color in COLOR_KEYS}
                        for r, c in cells:
                            counts[game.board[r][c]] += 1
                        regions.append(
                            {
                                "type": "eliminate",
                                "pos": [row, col],
                                "cells": cells,
                                "size": len(cells),
                                "counts": counts,
                            }
                        )
        return regions

    def deficits(game: HeadlessMatchGame) -> Dict[str, int]:
        return {
            color: max(0, game.color_targets[color] - game.color_counts[color])
            for color in COLOR_KEYS
        }

    def prop_candidates(game: HeadlessMatchGame) -> List[Dict[str, Any]]:
        remaining = deficits(game)
        candidates: List[Dict[str, Any]] = []

        if game.score >= COSTS["bomb"] and game.inventory.get("bomb", 0) > 0:
            for row in range(GRID_SIZE):
                for col in range(GRID_SIZE):
                    cells: List[List[int]] = []
                    counts = {color: 0 for color in COLOR_KEYS}
                    for dr in (-1, 0, 1):
                        for dc in (-1, 0, 1):
                            r, c = row + dr, col + dc
                            if 0 <= r < GRID_SIZE and 0 <= c < GRID_SIZE and game.board[r][c]:
                                cells.append([r, c])
                                counts[game.board[r][c]] += 1
                    target_hits = sum(min(counts[color], remaining[color]) for color in COLOR_KEYS)
                    if target_hits:
                        candidates.append(
                            {
                                "type": "bomb",
                                "pos": [row, col],
                                "cells": cells,
                                "size": len(cells),
                                "counts": counts,
                                "targetHits": target_hits,
                            }
                        )

        if game.score >= COSTS["row"] and game.inventory.get("row", 0) > 0:
            for row in range(GRID_SIZE):
                cells = [[row, col] for col in range(GRID_SIZE) if game.board[row][col]]
                counts = {color: 0 for color in COLOR_KEYS}
                for r, c in cells:
                    counts[game.board[r][c]] += 1
                target_hits = sum(min(counts[color], remaining[color]) for color in COLOR_KEYS)
                if target_hits:
                    candidates.append(
                        {
                            "type": "row",
                            "index": row,
                            "cells": cells,
                            "size": len(cells),
                            "counts": counts,
                            "targetHits": target_hits,
                        }
                    )

        if game.score >= COSTS["col"] and game.inventory.get("col", 0) > 0:
            for col in range(GRID_SIZE):
                cells = [[row, col] for row in range(GRID_SIZE) if game.board[row][col]]
                counts = {color: 0 for color in COLOR_KEYS}
                for r, c in cells:
                    counts[game.board[r][c]] += 1
                target_hits = sum(min(counts[color], remaining[color]) for color in COLOR_KEYS)
                if target_hits:
                    candidates.append(
                        {
                            "type": "col",
                            "index": col,
                            "cells": cells,
                            "size": len(cells),
                            "counts": counts,
                            "targetHits": target_hits,
                        }
                    )

        return candidates

    def choose_greedy(game: HeadlessMatchGame) -> Optional[Dict[str, Any]]:
        regions = connected_regions(game)
        if not regions:
            return None
        return max(regions, key=lambda action: (action["size"], sum(action["counts"].values())))

    def choose_target_aware(game: HeadlessMatchGame) -> Optional[Dict[str, Any]]:
        remaining = deficits(game)
        props = prop_candidates(game)
        if props:
            best_prop = max(
                props,
                key=lambda action: (action["targetHits"] * 10 + action["size"], action["targetHits"]),
            )
            if best_prop["targetHits"] >= 5 or sum(remaining.values()) <= 10:
                return best_prop

        regions = connected_regions(game)
        if regions:
            return max(
                regions,
                key=lambda action: (
                    sum(min(action["counts"][color], remaining[color]) for color in COLOR_KEYS) * 10
                    + action["size"],
                    action["size"],
                ),
            )
        if props:
            return props[0]
        return None

    def snapshot(game: HeadlessMatchGame) -> Dict[str, Any]:
        return {
            "board": deepcopy(game.board),
            "score": int(game.score),
            "stepsRemaining": int(game.steps_remaining),
            "stepsUsed": int(game.steps_used),
            "inventory": deepcopy(game.inventory),
            "counts": deepcopy(game.color_counts),
            "totalCleared": int(game.total_cleared),
            "cleared": all(
                game.color_counts[color] >= game.color_targets[color]
                for color in COLOR_KEYS
            ),
        }

    def execute_action(game: HeadlessMatchGame, action: Dict[str, Any]) -> bool:
        with contextlib.redirect_stdout(io.StringIO()):
            if action["type"] == "eliminate":
                row, col = action["pos"]
                region = game.find_connected_region(
                    row, col, game.board[row][col], [[False] * GRID_SIZE for _ in range(GRID_SIZE)], game.board
                )
                action["cells"] = region
                return bool(game.clear_region(region))
            if action["type"] == "row":
                return bool(game.use_prop("row", action["index"]))
            if action["type"] == "col":
                return bool(game.use_prop("col", action["index"]))
            if action["type"] == "bomb":
                return bool(game.use_prop("bomb", action["pos"]))
        return False

    def run_policy(name: str, seed: int) -> Dict[str, Any]:
        random.seed(seed)
        game = HeadlessMatchGame(level_data)
        frames: List[Dict[str, Any]] = []
        chooser = choose_greedy if name == "before" else choose_target_aware

        while not game.game_over and game.steps_remaining > 0:
            before = snapshot(game)
            action = chooser(game)
            if action is None:
                break
            score_before = game.score
            steps_before = game.steps_remaining
            counts_before = deepcopy(game.color_counts)
            inventory_before = deepcopy(game.inventory)
            success = execute_action(game, action)
            after = snapshot(game)
            frames.append(
                {
                    "beforeBoard": before["board"],
                    "afterBoard": after["board"],
                    "action": {
                        "type": action["type"],
                        "pos": action.get("pos"),
                        "index": action.get("index"),
                    },
                    "clearCells": action.get("cells", []),
                    "scoreBefore": int(score_before),
                    "scoreAfter": int(game.score),
                    "stepsBefore": int(steps_before),
                    "stepsAfter": int(game.steps_remaining),
                    "countsBefore": counts_before,
                    "countsAfter": deepcopy(game.color_counts),
                    "inventoryBefore": inventory_before,
                    "inventoryAfter": deepcopy(game.inventory),
                    "cleared": int(game.clear_counts[-1]) if game.clear_counts else 0,
                    "valid": bool(success),
                }
            )
            if not success:
                break

        labels = {
            "before": {
                "title": "Before memory: largest-cluster greedy",
                "phaseLabel": "executed easy level 05",
                "status": "fails B target after all steps",
                "truth": "No verified rule: score-heavy clears can leave a rare target color unfinished.",
            },
            "after": {
                "title": "After truth: target-aware prop timing",
                "phaseLabel": "executed easy level 05",
                "status": "targets met with steps left",
                "truth": "Verified rule: rank actions by unmet targets and save props for target-dense cells.",
            },
        }
        return {
            "policy": name,
            "source": "MatchGame.clear_region/use_prop on data/levels/match_game/easy/level05.json",
            **labels[name],
            "frameMs": 760,
            "targets": deepcopy(game.color_targets),
            "frames": frames,
            "metrics": snapshot(game),
        }

    return {
        "before": run_policy("before", seed=14),
        "after": run_policy("after", seed=14),
    }


def main() -> None:
    sys.path.insert(0, str(PROJECT_ROOT))
    data = {
        "generatedBy": "scripts/export_project_page_traces.py",
        "description": "Executed before/after traces for the project page learning comparison.",
        "maze": export_maze_trace(),
        "match2": export_match_trace(),
    }
    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_JSON.write_text(json.dumps(data, indent=2), encoding="utf-8")
    OUTPUT_JS.write_text(
        "// Generated by scripts/export_project_page_traces.py for local file previews.\n"
        f"window.EVOEMPIRBENCH_LEARNING_TRACES = {json.dumps(data, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUTPUT_JSON.relative_to(PROJECT_ROOT)}")
    print(f"Wrote {OUTPUT_JS.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
