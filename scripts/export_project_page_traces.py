#!/usr/bin/env python3
"""Export executed traces used by the project page.

The traces are generated by stepping the local EvoEmpirBench environments with
two transparent policies per task:
- before: a short-sighted policy without verified experience.
- after: a memory-conditioned policy that uses the relevant verified rule.

Only UI/framework imports are stubbed when missing so this script can run in
headless documentation environments. Game transitions still come from the
project environment methods (`PathFindingEnv.step`, `MatchGame.clear_region`,
and `MatchGame.use_prop`).
"""

from __future__ import annotations

